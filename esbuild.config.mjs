import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
const devPluginDirectory = process.env.FLOW_DEV_PLUGIN_DIR;

/** Copies the build into a vault plugin folder under a dev id and name, so it never clashes with the released plugin. */
async function installToVault(directory) {
	const manifest = JSON.parse(await readFile('manifest.json', 'utf8'));
	const devManifest = { ...manifest, id: `dev-${manifest.id}`, name: `Dev ${manifest.name}` };
	await mkdir(directory, { recursive: true });
	await writeFile(join(directory, 'manifest.json'), JSON.stringify(devManifest, null, '\t'));
	await copyFile('main.js', join(directory, 'main.js'));
	await copyFile('styles.css', join(directory, 'styles.css'));
}

const installToVaultPlugin = {
	name: 'install-to-vault',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0 || !devPluginDirectory) return;
			return installToVault(devPluginDirectory);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	plugins: [installToVaultPlugin],
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
